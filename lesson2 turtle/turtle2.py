# ===================================================
# turtle2.py - צבעים, עובי ומהירות 🎨
# ===================================================

import turtle

screen = turtle.Screen() # המסך (הדף) שעליו הצב מצייר
screen.bgcolor("lightblue") # צבע רקע
screen.title("הצב הצבעוני שלי") # הכותרת של החלון

t = turtle.Turtle()
t.shape("arrow")
t.speed(1) # מהירות: 1 = איטי, 10 = מהיר, 0 = הכי מהיר שיש
t.pensize(5) # עובי העט

# --- משולש שכל צלע שלו בצבע אחר ---
t.color("green") # צבע העט (וגם של הצב)
t.forward(150)
t.left(120)

t.color("green")
t.forward(150)
t.left(120)

t.color("blue")
t.forward(150)
t.left(120)

turtle.done()

# ===================================================
# 🏆 אתגרים:
# ===================================================
# 1. שנו את צבע הרקע ל-"lightblue" ואת עובי העט ל-10.
# 2. נסו צורות אחרות לצב: "arrow", "circle", "square", "triangle", "classic"
# 3. ציירו ריבוע שכל צלע שלו בצבע אחר (צבעים: "orange", "purple", "pink"...)
# 4. אפשר גם צבע לפי קוד: t.color("#FF00FF") - נסו!
# 5. בונוס: שמרו את המהירות במשתנה בשם my_speed והשתמשו בו: t.speed(my_speed)
