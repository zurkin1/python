# ===================================================
# turtle3.py - מרימים את העט, קופצים ומציירים עיגולים 😃
# ===================================================
# מפת המסך: הנקודה (0, 0) נמצאת באמצע.
# x גדל ימינה, y גדל למעלה.

import turtle

t = turtle.Turtle()
t.speed(6)
t.pensize(4)

# --- הפנים: עיגול גדול ---
t.penup() # מרימים את העט - זזים בלי לצייר
t.goto(0, -100) # קופצים לנקודה (x=0, y=-100)
t.pendown() # מורידים את העט - שוב מציירים
t.color("orange")
t.circle(100) # עיגול ברדיוס 100 (הצב מצייר אותו נגד כיוון השעון)

# --- עין שמאל ---
t.penup()
t.goto(-35, 30)
t.pendown()
t.color("black")
t.dot(25) # נקודה עגולה מלאה בקוטר 25

# --- עין ימין ---
t.penup()
t.goto(35, 30)
t.pendown()
t.dot(25)

# --- חיוך: חצי עיגול ---
t.penup()
t.goto(-50, -20)
t.setheading(-60) # מסובבים את הצב לכיוון מדויק (0 = ימינה, 90 = למעלה)
t.pendown()
t.color("red")
t.circle(58, 120) # רק 120 מעלות מתוך העיגול = קשת

t.hideturtle() # מסתירים את הצב כדי שהציור ייראה נקי

turtle.done()

