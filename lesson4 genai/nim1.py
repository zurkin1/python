# שלב 1: יש ערימה אחת של 55 אסימונים. בכל תור מורידים 1 עד 10 אסימונים.
# input שואל את השחקן כמה אסימונים לקחת, ואנחנו מעדכנים את הערימה.

pile = 55 # כמה אסימונים יש בערימה
MAX_TAKE = 10 # כמה אסימונים מותר לקחת בתור אחד
MAX_TURNS = 10 # כמה תורות נשחק

print("Let's play NIM!")
print("Take 1 to " + str(MAX_TAKE) + " tokens in each turn.")

for turn in range(MAX_TURNS):
    print()
    print("*" * pile) # כוכבית לכל אסימון
    print("Tokens left: " + str(pile))
    count = int(input("How many tokens do you take? ")) # input מחזיר מחרוזת - int הופך למספר
    pile = pile - count # מורידים אסימונים מהערימה

print("Game over. Tokens left: " + str(pile))

