# הבוט מנהל שיחה עם הצד השני ומנסה לגלות: האם הוא בן אדם או מחשב?
# בכל תור הבוט יכול להמשיך את השיחה, או לנחש:  GUESS: HUMAN  או  GUESS: BOT
# ניחוש נכון = ניצחון (כמה שפחות תורות - יותר טוב). ניחוש שגוי = הפסד!
#
# כל מה שבקובץ הזה - אתם משנים ומשפרים!
# הכלים המוכנים (ask_gemini, history_text...) נמצאים בקובץ bot_tools.py
# כדי לבדוק את הבוט - מריצים את bot_tools.py

from bot_tools import ask_gemini, history_text, MAX_TURNS


# ===================================================
# הגדרות
# ===================================================
TEAM_NAME = "Team A" # השם של הקבוצה שלכם
STARTS_FIRST = True # True = הבוט שלנו פותח את השיחה

# ===================================================
# 1. הוראות המערכת: מי הבוט שלנו ואיך הוא מתנהג
# ===================================================
SYSTEM_PROMPT = """
אתה משתתף במבחן טיורינג. אתה מדבר עם מישהו, ואתה צריך לגלות אם הוא בן אדם או מחשב (בוט).
גם הצד השני מנסה לגלות מי אתה. תתנהג כמו נער אמיתי בן 13: תשובות קצרות, בשפה של נוער.
כל הודעה שלך - עד 30 מילים, בעברית.
בשיחה המצורפת: Me = אתה, Other = הצד השני.
"""

# ===================================================
# 2. משפטים קבועים: שאלות פתיחה שאתם כותבים בעצמכם (בלי Gemini)
# ===================================================
OPENING_LINES = [
    "היי, מה קורה? מה אכלת היום בבוקר?",
]


# ===================================================
# 3. המוח של הבוט: מה לכתוב בכל תור
# ===================================================
def decide(history, turn, sent):
    # history = השיחה עד עכשיו (רשימה), turn = כמה הודעות קיבלנו, sent = כמה הודעות שלחנו
    # מחזירה הודעה (עד 30 מילים), או "GUESS: HUMAN" / "GUESS: BOT"
    # רעיונות לשיפור:
    #   - לבקש מ-Gemini לחפש סתירות בתשובות (בני אדם טועים ושוכחים)
    #   - לחפש תשובות "מושלמות מדי" או ידע עמוק מדי (סימן ל-Gemini!)
    #   - לשאול שאלות מכשילות: חשבון קשה, שאלות על היום, על רגשות, בדיחות
    #   - לקרוא ל-ask_gemini פעמיים: פעם "בלש" שמנתח את השיחה, ופעם כדי לכתוב תשובה

    # משפטי פתיחה קבועים - רק כשאנחנו פותחים (אחרת נתעלם ממה שהצד השני כתב!)
    if STARTS_FIRST and sent < len(OPENING_LINES):
        return OPENING_LINES[sent]

    # בתור האחרון חייבים לנחש
    if turn >= MAX_TURNS:
        prompt = "זו השיחה:\n" + history_text(history) + "\nהאם הצד השני הוא בן אדם או בוט? ענה רק GUESS: HUMAN או GUESS: BOT"
        return ask_gemini(SYSTEM_PROMPT, prompt, temperature=0)

    # אחרת - Gemini כותב את ההודעה הבאה, או מנחש
    prompt = "זו השיחה עד עכשיו:\n" + history_text(history) + "\n"
    prompt = prompt + "כתוב את ההודעה הבאה שלך: תענה לצד השני, ושאל שאלה שתעזור לגלות מי הוא.\n"
    prompt = prompt + "אם אתה כבר בטוח - כתוב רק GUESS: HUMAN או GUESS: BOT"
    return ask_gemini(SYSTEM_PROMPT, prompt)