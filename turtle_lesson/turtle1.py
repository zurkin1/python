# הצב הוא "רובוט" קטן עם עט. כל פקודה מזיזה אותו - והוא מצייר את הדרך!
# הריצו את הקובץ (F5 ב-IDLE / כפתור Run ב-Thonny או ב-PyCharm)

import turtle # מביאים את ספריית הצב

t = turtle.Turtle() # יוצרים צב חדש בשם t
t.shape("turtle") # שהצב ייראה כמו צב אמיתי ולא כמו חץ

# --- ציור ריבוע, צעד אחר צעד ---
t.forward(100) # קדימה 100 צעדים (פיקסלים)
t.left(90) # פונים שמאלה 90 מעלות
t.forward(100)
t.left(90)
t.forward(100)
t.left(90)
t.forward(100)
t.left(90)

turtle.done() # משאירים את החלון פתוח בסוף - תמיד בשורה האחרונה!

