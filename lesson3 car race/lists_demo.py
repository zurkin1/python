import turtle

# --- חלק 1: רשימה ב-print ---
colors = ["red", "orange", "yellow", "green", "blue"]

print(colors) # כל הרשימה
print(colors[0]) # האיבר הראשון - האינדקס מתחיל מ-0!
print(colors[-1]) # האיבר האחרון
print(len(colors)) # כמה איברים יש ברשימה

colors.append("purple") # מוסיפים איבר לסוף הרשימה
colors[1] = "pink" # מחליפים איבר
print(colors)

# --- חלק 2: לולאה על רשימה + הצב ---
t = turtle.Turtle()
t.speed(0)
t.pensize(8)

for color in colors: # color מקבל כל פעם צבע אחר מהרשימה
    t.color(color)
    t.circle(60)
    t.left(360 / len(colors))

t.hideturtle()
turtle.done()

